if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $action = $_POST['action'] ?? '';

    if ($action === 'setup_db') {
        $host = trim($_POST['db_host'] ?? 'localhost');
        $port = (int)($_POST['db_port'] ?? 3306);
        $dbName = trim($_POST['db_name'] ?? '');
        $dbUser = trim($_POST['db_user'] ?? '');
        $dbPass = (string)($_POST['db_pass'] ?? '');
        $appUrl = rtrim(trim($_POST['app_url'] ?? ''), '/');

        try {
            $dsn = sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $host, $port, $dbName);
            $pdo = new PDO($dsn, $dbUser, $dbPass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            ]);

            if (!file_exists($schemaFile)) {
                throw new RuntimeException('Schema file missing at /database/schema.sql');
            }

            $sql = file_get_contents($schemaFile);
            $pdo->exec($sql);

            $secretKey = bin2hex(random_bytes(32));
            $configPhp = "<?php\n/**\n * Generated by SMM PRO Installer\n */\nreturn " . var_export([
                'db' => [
                    'host'     => $host,
                    'port'     => $port,
                    'database' => $dbName,
                    'username' => $dbUser,
                    'password' => $dbPass,
                    'charset'  => 'utf8mb4',
                ],
                'app' => [
                    'url'           => $appUrl ?: ('http://' . ($_SERVER['HTTP_HOST'] ?? 'localhost')),
                    'secret_key'    => $secretKey,
                    'env'           => 'production',
                    'debug'         => false,
                    'session_name'  => 'SMMPRO_SESSID',
                    'admin_session' => 'SMMPRO_ADMIN_SESSID',
                ],
            ], true) . ";\n";

            if (file_put_contents($configFile, $configPhp) === false) {
                throw new RuntimeException('Failed to write /config/config.php');
            }

            header('Location: /install/index.php?step=3');
            exit;
        } catch (Throwable $e) {
            $error = 'Database setup failed: ' . $e->getMessage();
            $step = 2;
        }
    } elseif ($action === 'create_admin') {
        if (!file_exists($configFile)) {
            $error = 'Configuration file missing. Please complete Step 2 first.';
            $step = 2;
        } else {
            $cfg = require $configFile;
            $fullName = trim($_POST['full_name'] ?? 'Super Admin');
            $username = trim($_POST['username'] ?? '');
            $email = strtolower(trim($_POST['email'] ?? ''));
            $password = (string)($_POST['password'] ?? '');
            $siteName = trim($_POST['site_name'] ?? 'SMM PRO');

            if (!preg_match('/^[a-zA-Z0-9_.-]{3,50}$/', $username)) {
                $error = 'Admin username must be 3-50 alphanumeric characters.';
                $step = 3;
            } elseif (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
                $error = 'Please enter a valid admin email address.';
                $step = 3;
            } elseif (strlen($password) < 8) {
                $error = 'Password must be at least 8 characters long.';
                $step = 3;
            } else {
                try {
                    $dsn = sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $cfg['db']['host'], $cfg['db']['port'], $cfg['db']['database']);
                    $pdo = new PDO($dsn, $cfg['db']['username'], $cfg['db']['password'], [
                        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    ]);

                    $hash = password_hash($password, PASSWORD_DEFAULT);
                    $stmt = $pdo->prepare(
                        "INSERT INTO admins (role_id, username, email, password_hash, full_name, status)
                         VALUES (1, ?, ?, ?, ?, 'active')"
                    );
                    $stmt->execute([$username, $email, $hash, $fullName]);

                    $sStmt = $pdo->prepare("UPDATE settings SET setting_value = ? WHERE setting_key = 'site_name'");
                    $sStmt->execute([$siteName]);

                    @file_put_contents($lockFile, 'Installed on ' . date('c'));
                    header('Location: /install/index.php?step=4');
                    exit;
                } catch (Throwable $e) {
                    $error = 'Failed to create Super Admin: ' . $e->getMessage();
                    $step = 3;
                }
            }
        }
    }
}
